#!/bin/bash
# Assembles lumac.app from the SwiftPM executable.
#
# No Xcode required — SwiftPM builds the binary, and the bundle is laid out by
# hand here. Install Xcode later if you need notarisation or Instruments.
set -euo pipefail
cd "$(dirname "$0")"

CONFIG="${1:-debug}"
APP="build/lumac.app"

# Single source of truth for the version.
#
# It used to be typed here *and* in LumacVersion, which is what the in-app
# update check compares against the GitHub release tag — so a drift between
# the two would make the app misreport whether it is up to date. The Swift
# constant wins; this reads it out.
VERSION="$(sed -n 's/.*static let number = "\(.*\)".*/\1/p' \
  Sources/lumac/Views/RootView.swift)"
if [ -z "$VERSION" ]; then
  echo "error: could not read LumacVersion.number from RootView.swift" >&2
  exit 1
fi

# Pinned to the 26.5 SDK on purpose.
#
# In the 27.0 SDK, SwiftUI's @State is a macro backed by SwiftUIMacros, and the
# Command Line Tools do not ship libSwiftUIMacros.dylib — only Xcode does. Until
# Xcode is installed, building against 27.0 fails on every @State in the project.
# Remove this block once Xcode is present.
SDK_PIN="/Library/Developer/CommandLineTools/SDKs/MacOSX26.5.sdk"
if [ -z "${SDKROOT:-}" ] && [ -d "$SDK_PIN" ] && \
   [ ! -f "$(xcrun --find swift-frontend 2>/dev/null | xargs dirname)/../lib/swift/host/plugins/libSwiftUIMacros.dylib" ]; then
  export SDKROOT="$SDK_PIN"
  echo "note: building against $(basename "$SDK_PIN") (no SwiftUIMacros plugin available)"
fi

swift build -c "$CONFIG"
BIN="$(swift build -c "$CONFIG" --show-bin-path)"

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

cp "$BIN/lumac" "$APP/Contents/MacOS/lumac"
# Bundle.module looks in Bundle.main.resourceURL first, which for an app bundle
# is Contents/Resources. A second copy beside the binary covers the layout the
# other SwiftPM build system produces.
cp -R "$BIN/lumac_lumac.bundle" "$APP/Contents/Resources/" 2>/dev/null || true
cp -R "$BIN/lumac_lumac.bundle" "$APP/Contents/MacOS/" 2>/dev/null || true

# App icon. appicon.png is the 1024×1024 lumac crescent, generated by
# Tools/makelumac.swift and used directly — macOS applies the rounded mask.
APP_ICON="Sources/lumac/Resources/appicon.png"

if command -v iconutil >/dev/null && command -v sips >/dev/null && [ -f "$APP_ICON" ]; then
  ICONSET="build/lumac.iconset"
  rm -rf "$ICONSET"; mkdir -p "$ICONSET"
  for size in 16 32 64 128 256 512; do
    sips -z $size $size "$APP_ICON" \
      --out "$ICONSET/icon_${size}x${size}.png" >/dev/null 2>&1 || true
    sips -z $((size*2)) $((size*2)) "$APP_ICON" \
      --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null 2>&1 || true
  done
  iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/lumac.icns" 2>/dev/null || true
  rm -rf "$ICONSET"
fi

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>lumac</string>
  <key>CFBundleDisplayName</key><string>lumac</string>
  <key>CFBundleIdentifier</key><string>app.lumac.ui</string>
  <key>CFBundleExecutable</key><string>lumac</string>
  <key>CFBundleIconFile</key><string>lumac</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$VERSION</string>
  <key>LSMinimumSystemVersion</key><string>26.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSSupportsAutomaticTermination</key><false/>
</dict>
</plist>
PLIST

# Code signature.
#
# We sign with a stable self-signed identity ("lumac-selfsign") when it exists in
# the keychain, and fall back to an ad-hoc signature otherwise. The stable
# identity matters: macOS ties Full Disk Access (and other TCC grants) to the
# app's Designated Requirement, which for this identity is anchored to the
# certificate — not the binary hash — so a grant survives every rebuild. Ad-hoc
# has no such identity, so each rebuild looks like a new app and must be
# re-authorized. Create the identity once with: ./scripts/make-signing-cert.sh
SIGN_ID="${LUMAC_SIGN_ID:-lumac-selfsign}"
if security find-identity -p codesigning 2>/dev/null | grep -q "\"$SIGN_ID\""; then
  codesign --force --deep --sign "$SIGN_ID" "$APP" >/dev/null 2>&1 \
    && echo "signed with $SIGN_ID" \
    || { echo "warning: signing with $SIGN_ID failed, falling back to ad-hoc"; \
         codesign --force --deep --sign - "$APP" >/dev/null 2>&1 || true; }
else
  echo "note: '$SIGN_ID' not in keychain — ad-hoc signing (FDA will reset each rebuild)."
  echo "      run ./scripts/make-signing-cert.sh once to fix that."
  codesign --force --deep --sign - "$APP" >/dev/null 2>&1 || true
fi

echo "built $APP (v$VERSION)"
